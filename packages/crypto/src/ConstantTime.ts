import type { Redacted } from "effect";
import { Effect } from "effect";
import type { CryptoError } from "effect/crypto";
import { Mac } from "effect/crypto";
import { secretBytes, utf8 } from "./internal/bytes.js";

/**
 * Secret material for {@link ConstantTime.secretsEqual}: bytes, a string, or
 * a `Redacted` string.
 *
 * @remarks
 * Strings, redacted or not, are compared as their UTF-8 bytes.
 *
 * @public
 */
export type SecretInput = Uint8Array | string | Redacted.Redacted<string>;

const equal = (a: Uint8Array | string, b: Uint8Array | string): boolean => Mac.timingSafeEqual(utf8(a), utf8(b));

const secretsEqual = (
	expected: SecretInput,
	received: SecretInput,
): Effect.Effect<boolean, CryptoError.CryptoError, Mac.Mac> =>
	Effect.gen(function* () {
		const mac = yield* Mac.Mac;
		// A fresh key per comparison: the MACs it produces are never seen
		// outside this call, so blinding with it reveals nothing.
		const key = yield* mac.generateKey(Mac.hmacSha256);
		const tag = yield* mac.sign(key, secretBytes(expected));
		// `verify` recomputes the received side's MAC under the same key and
		// compares the two 32-byte tags in constant time.
		return yield* mac.verify(key, tag, secretBytes(received));
	});

/**
 * Comparison whose running time does not depend on where two values differ.
 *
 * @remarks
 * The guarantee is best-effort: the comparison is core's
 * `Mac.timingSafeEqual` (or, for {@link ConstantTime.secretsEqual}, the `Mac`
 * layer's own constant-time verify), and a JavaScript engine is free to
 * optimise a loop. Compare a fixed-length digest with
 * {@link ConstantTime.equal}; compare a shared secret with
 * {@link ConstantTime.secretsEqual}, which blinds both sides with a keyed MAC
 * first so neither the secret's length nor a matching prefix can leak.
 *
 * @public
 */
export class ConstantTime {
	private constructor() {}

	/**
	 * Whether `a` and `b` hold the same bytes.
	 *
	 * @remarks
	 * Strings are compared as their UTF-8 bytes, so a string and the bytes of
	 * its UTF-8 encoding are equal. The bytes go to core's
	 * `Mac.timingSafeEqual`, which visits every byte with no early return on a
	 * mismatch. A length mismatch returns `false`
	 * immediately, which reveals the length; that is harmless for digests and
	 * MACs, whose length is public.
	 *
	 * @public
	 */
	static readonly equal: (a: Uint8Array | string, b: Uint8Array | string) => boolean = equal;

	/**
	 * Whether two secrets are equal, compared through their HMACs under a
	 * fresh random key.
	 *
	 * @remarks
	 * Each call generates an HMAC-SHA256 key with `Mac.generateKey`, MACs the
	 * expected side under it and checks the received side with `Mac.verify`,
	 * which compares the two 32-byte MACs in constant time: the secret's length
	 * and any matching prefix never reach the comparison, and the blinding is
	 * keyed, so its output cannot be precomputed. Use it for a shared-secret
	 * header. A `Redacted` value is read only to MAC it.
	 *
	 * Requires `Mac.Mac` (`effect/crypto`) in `R`: `Mac.layerWebCrypto` with
	 * `SecureRandom.layerWebCrypto`, or a platform family layer such as
	 * `NodeCrypto.layerMac`. The error channel is core's `CryptoError`, which
	 * only a misbehaving `Mac` layer reaches: the key is generated by the layer
	 * itself. On the WebCrypto layer, a runtime with no `crypto.subtle` dies
	 * rather than failing.
	 *
	 * On `Mac.layerWebCrypto` this is truly asynchronous: a test that forks it
	 * and then adjusts `TestClock` can race or hang; await it or gate the
	 * clock on a latch.
	 *
	 * @public
	 */
	static readonly secretsEqual: (
		expected: SecretInput,
		received: SecretInput,
	) => Effect.Effect<boolean, CryptoError.CryptoError, Mac.Mac> = secretsEqual;
}
