// Chooses the corpus sample: the fixtures a pull request run compares on. Run it through the package script,
//
//   pnpm --filter @effected/markdown-lint run corpus:sample            (print the choice)
//   pnpm --filter @effected/markdown-lint run corpus:sample --write    (rewrite corpus-sample.ts)
//
// It reads the fixtures directly, never through the sample it is about to replace, so a stale sample cannot stop it.
//
// Two steps, both deterministic:
//
// 1. Named fixtures. Every corpus fixture a test names by file name is in the sample: those are the recorded
//    divergences and the inputs markdownlint itself throws on, which are the cases most worth a pull request's time,
//    and a test that pins what happens on a fixture must find it at every depth.
// 2. Rule cover. A cheap set of fixtures (greedy by rules gained per byte, ties by name) in which every rule
//    markdownlint reports anywhere in the corpus reports somewhere. A pass costs time in proportion to the bytes it
//    lints, so a few small fixtures beat one large one.
//
// The sample is deliberately this small. Each rule's own hand-written inputs run at every depth and carry nearly all
// of the source coverage: measured when the sample was chosen, this package's source was covered 99.36% by line and
// 93.38% by branch at sample depth against 99.51% and 94.00% over the whole corpus. Growing the sample to reach 95%
// of the source the corpus executes bought ten more branches and nearly doubled the run. Re-measure both depths when
// the sample changes (the command is in okf/modules/markdown-lint.md); if the two drift more than a point apart, add
// fixtures here rather than accept the gap.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";
import { fullCorpus } from "./corpus-files.js";
import { chooseCover, ruleCovers, uncovered } from "./sample-cover.js";

const argv = process.argv.slice(2);
// pnpm forwards a literal `--` ahead of the flags; drop one leading occurrence.
if (argv[0] === "--") argv.shift();
const { values: flags } = parseArgs({ args: argv, options: { write: { type: "boolean", default: false } } });

// Step 1. A fixture name in quotes, with or without the ` (CRLF)` or ` (CR)` a divergence list adds to it.
const testsDir = join(import.meta.dirname, "..");
const fixtureNames = new Set(fullCorpus.map((entry) => entry.name));
const named = new Set<string>();
for (const file of readdirSync(testsDir, { recursive: true, encoding: "utf8" })) {
	if (!file.endsWith(".test.ts")) continue;
	const text = readFileSync(join(testsDir, file), "utf8");
	for (const match of text.matchAll(/["'`]([^"'`\n]+?\.md)(?: \((?:CRLF|CR)\))?["'`]/g)) {
		const name = match[1];
		if (name !== undefined && fixtureNames.has(name)) named.add(name);
	}
}

// Step 2.
const costs = new Map(fullCorpus.map((entry) => [entry.name, Math.max(entry.source.length, 1)]));
const ruleCover = ruleCovers(fullCorpus);
const byRule = chooseCover(ruleCover, costs);

const sample = [...new Set([...named, ...byRule])].sort();
const rulesReported = new Set<string>();
for (const found of ruleCover.values()) for (const name of found) rulesReported.add(name);
const bytes = (list: ReadonlyArray<string>): number => list.reduce((total, name) => total + (costs.get(name) ?? 0), 0);

console.log(`corpus: ${fullCorpus.length} fixtures, ${rulesReported.size} rules reported`);
console.log(`named by a test: ${named.size} fixtures; rule cover: ${byRule.length} fixtures`);
console.log(
	`sample: ${sample.length} fixtures, ${((bytes(sample) / bytes([...costs.keys()])) * 100).toFixed(1)}% of the corpus by size, ` +
		`rules left uncovered: ${JSON.stringify(uncovered(ruleCover, sample))}`,
);

const file = `// Generated by \`pnpm --filter @effected/markdown-lint run corpus:sample --write\`. Do not edit by hand:
// rerun the script, which chooses the list (see choose-sample.ts for how).
//
// The fixtures of the upstream markdownlint corpus that a pull request run compares on. The full corpus runs at
// full depth (EFFECTED_TEST_DEPTH=full): for a release, and on demand.
export const CORPUS_SAMPLE: ReadonlyArray<string> = [
${sample.map((name) => `\t${JSON.stringify(name)},`).join("\n")}
];
`;

if (flags.write) {
	writeFileSync(join(import.meta.dirname, "corpus-sample.ts"), file);
	console.log("wrote corpus-sample.ts");
} else {
	console.log(sample.join("\n"));
}
