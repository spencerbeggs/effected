import { MarkdownVisitor } from "@effected/markdown";
import { LintRule } from "../../src/LintRule.js";
import { RULE_DOCS } from "./docs.js";

export const HeadingHierarchy = LintRule.make({
	names: ["changeset-heading-hierarchy", "CSH001"],
	description: "Heading hierarchy must start at h2 with no h1 or depth skips",
	tags: ["changeset"],
	check: (context, report) => {
		let previous = 0;
		MarkdownVisitor.traverse(context.root, "heading", {
			enter: (heading) => {
				if (heading.depth === 1) {
					report(
						context.diagnostic({
							at: heading,
							detail: `h1 headings are not allowed in changeset files. Use h2 (##) for top-level sections like "## Features" or "## Bug Fixes". h1 is reserved for the version title generated by the changelog formatter. See: ${RULE_DOCS.CSH001}`,
						}),
					);
					return undefined;
				}
				if (previous > 0 && heading.depth > previous + 1) {
					report(
						context.diagnostic({
							at: heading,
							detail: `Heading level skipped: expected h${previous + 1} or lower, found h${heading.depth}. Headings must increase sequentially (h2 → h3 → h4). Add the missing intermediate level or reduce this heading's depth. See: ${RULE_DOCS.CSH001}`,
						}),
					);
				}
				previous = heading.depth;
				return undefined;
			},
		});
	},
});
