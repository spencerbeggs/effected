// Copies markdownlint's test/*.md fixtures from the vendored submodule into
// __test__/fixtures/markdownlint/ and writes a README naming the upstream tag.
// Takes no arguments; idempotent. Run: node packages/markdown-lint/scripts/capture-markdownlint-corpus.mjs
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..", "..", "..");
const source = join(root, ".repos", "markdownlint");
const target = join(here, "..", "__test__", "fixtures", "markdownlint");

const git = (...args) => execFileSync("git", ["-C", source, ...args], { encoding: "utf8" }).trim();

const commit = git("rev-parse", "HEAD");
const tag = git("tag", "--points-at", "HEAD").split("\n")[0] || git("describe", "--tags", "--always");

const names = readdirSync(join(source, "test"))
	.filter((name) => name.endsWith(".md"))
	.sort();

mkdirSync(target, { recursive: true });
for (const name of readdirSync(target)) {
	if (name.endsWith(".md") && name !== "README.md" && !names.includes(name)) {
		rmSync(join(target, name));
	}
}
for (const name of names) {
	// The vendored tree is read-only, so copy the bytes rather than the mode.
	rmSync(join(target, name), { force: true });
	writeFileSync(join(target, name), readFileSync(join(source, "test", name)));
}

writeFileSync(
	join(target, "README.md"),
	[
		"# markdownlint fixture corpus",
		"",
		"Byte-identical copies of upstream `test/*.md` from DavidAnson/markdownlint.",
		"Generated by `scripts/capture-markdownlint-corpus.mjs`; do not edit by hand.",
		"",
		`- Upstream tag: \`${tag}\``,
		`- Upstream commit: \`${commit}\``,
		`- File count: ${names.length}`,
		"",
	].join("\n"),
);

console.log(`${names.length} fixtures copied from ${tag} (${commit})`);
