import { readFileSync } from "node:fs";
import { assert, describe, it } from "@effect/vitest";
import { OUTPUT, extract, generate, render } from "../lib/scripts/generate-rest-setting-keys.js";
import { GRAPHQL_ONLY_SETTINGS } from "../src/GitHubRepository.js";
import { REPOSITORY_REST_SETTING_KEYS } from "../src/internal/repositoryRestSettingKeys.js";

/**
 * The REST allowlist is generated, committed, and checked here: a bump of
 * `@octokit/openapi-types` that moves the key set fails this suite until the
 * generator is re-run.
 */
describe("repositoryRestSettingKeys", () => {
	it("the committed file is what the generator produces from the installed octokit types", () => {
		assert.strictEqual(readFileSync(OUTPUT, "utf8"), generate());
	});

	it("carries the keys the package itself writes, and none it routes elsewhere by mistake", () => {
		// Positive control: an empty or truncated extraction would still match a
		// file generated by the same bug, so pin keys the code depends on.
		for (const key of ["has_issues", "has_wiki", "security_and_analysis", "allow_merge_commit", "merge_commit_title"]) {
			assert.isTrue(REPOSITORY_REST_SETTING_KEYS.has(key), key);
		}
		// The keys effected#358 found the REST PATCH silently ignoring.
		assert.isFalse(REPOSITORY_REST_SETTING_KEYS.has("has_discussions"));
		assert.isFalse(REPOSITORY_REST_SETTING_KEYS.has("has_sponsorships"));
		// Still declared by the octokit description, removed by api-version
		// 2026-03-10: the REST PATCH would ignore it and answer 200.
		assert.isFalse(REPOSITORY_REST_SETTING_KEYS.has("use_squash_pr_title_as_default"));
		assert.isAbove(Object.keys(GRAPHQL_ONLY_SETTINGS).length, 0);
	});

	it("extracts only top-level body keys, quoted or bare, sorted and deduplicated", () => {
		const source = `export interface operations {
  "repos/update": {
    requestBody?: {
      content: {
        "application/json": {
          zeta?: string;
          "alpha"?: boolean;
          nested?: { inner?: string };
        };
      };
    };
  };
}`;
		assert.deepStrictEqual([...extract(source)], ["alpha", "nested", "zeta"]);
	});

	it("fails loudly when the shape it walks moves", () => {
		assert.throws(() => extract(`export interface operations { "repos/get": {} }`), /no property repos\/update/);
		assert.throws(
			() =>
				extract(
					`export interface operations { "repos/update": { requestBody?: { content: { "application/json": X } } } }`,
				),
			/expected an inline type literal/,
		);
	});

	it("renders a header naming the source and version", () => {
		const text = render(["a"], "1.2.3");
		assert.match(text, /GENERATED FILE/);
		assert.match(text, /@octokit\/openapi-types@1\.2\.3/);
	});
});
